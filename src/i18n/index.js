const currentLang = ref(localStorage.getItem('wordmagic-lang') || 'en')

export function setLang(lang) {
  currentLang.value = lang
  localStorage.setItem('wordmagic-lang', lang)
}

export function getLang() {
  return currentLang.value
}

export function t(key) {
  return computed(() => messages[currentLang.value]?.[key] || messages.en?.[key] || key)
}

export function useI18n() {
  return {
    lang: currentLang,
    t,
    setLang
  }
}
